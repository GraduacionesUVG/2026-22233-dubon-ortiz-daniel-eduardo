type AnthropicClient struct {
	client      anthropic.Client
	model       string
	temperature float64
	workoutRepo ports.WorkoutRepository
	chatRepo    ports.ChatRepository
	userRepo    ports.UserRepository
	location    *time.Location // users' timezone, used to decide what "today" means
}

func NewAnthropicClient(apiKey string, workoutRepo ports.WorkoutRepository, chatRepo ports.ChatRepository, userRepo ports.UserRepository, location *time.Location) ports.LLMService {
	client := anthropic.NewClient(option.WithAPIKey(apiKey))

	model := os.Getenv("ANTHROPIC_MODEL")
	if model == "" {
		model = defaultModel
	}
	slog.Info("Using Anthropic model", "model", model, "temperature", defaultTemperature)

	return &AnthropicClient{
		client:      client,
		model:       model,
		temperature: defaultTemperature,
		workoutRepo: workoutRepo,
		chatRepo:    chatRepo,
		userRepo:    userRepo,
		location:    location,
	}
}

// now returns the current time in the users' timezone instead of the server's
func (c *AnthropicClient) now() time.Time {
	return time.Now().In(c.location)
}

func (c *AnthropicClient) GenerateRoutine(ctx context.Context, user domain.User, contextInfo string, onTextChunk func(string)) (domain.Workout, error) {
	slog.Info("Starting LLM workout generation", "user_id", user.ID, "user_name", user.Name)

	// Get Gimpy tools for Claude to use
	tools := GetGimpyTools()

	// Convert tools to Anthropic format
	anthropicTools := make([]anthropic.ToolUnionParam, len(tools))
	for i, tool := range tools {
		toolJSON, err := json.Marshal(tool)
		if err != nil {
			slog.Error("Failed to marshal tool", "tool_index", i, "error", err)
			return domain.Workout{}, fmt.Errorf("failed to marshal tool: %w", err)
		}

		var toolParam anthropic.ToolUnionParam
		if err := json.Unmarshal(toolJSON, &toolParam); err != nil {
			slog.Error("Failed to unmarshal tool param", "tool_index", i, "error", err)
			return domain.Workout{}, fmt.Errorf("failed to unmarshal tool param: %w", err)
		}
		anthropicTools[i] = toolParam
	}

	// Load recent chat history (short-term memory)
	chatHistory, err := c.chatRepo.GetRecentChatHistory(ctx, user.ID, 10)
	if err != nil {
		slog.Error("Failed to load chat history", "user_id", user.ID, "error", err)
		chatHistory = []domain.ChatMessage{} // Continue without history
	}

	// Build conversation messages starting with history
	messages := []anthropic.MessageParam{}

	// Add historical messages to conversation
	for _, msg := range chatHistory {
		if msg.Role == "user" {
			messages = append(messages, anthropic.NewUserMessage(anthropic.NewTextBlock(msg.Content)))
		} else if msg.Role == "assistant" {
			messages = append(messages, anthropic.NewAssistantMessage(anthropic.NewTextBlock(msg.Content)))
		}
	}

	// Build current user message with context
	// Extract injury descriptions for display
	injuryDescriptions := make([]string, len(user.Injuries))
	for i, injury := range user.Injuries {
		injuryDescriptions[i] = injury.Description
	}

	userMessage := fmt.Sprintf(`User Profile:
- Name: %s
- Fitness Goals: %v
- Known Injuries: %v

User's Request:
%s

Respond according to the SUPREME INSTRUCTION in your system prompt. Determine the user's intention first before taking any action.`, user.Name, user.FitnessGoals, injuryDescriptions, contextInfo)

	// Add current user message to conversation
	messages = append(messages, anthropic.NewUserMessage(anthropic.NewTextBlock(userMessage)))

	slog.Info("Sending workout context to LLM",
		"user_id", user.ID,
		"fitness_goals", user.FitnessGoals,
		"injuries", injuryDescriptions,
		"prompt", contextInfo)

	// Save user message to chat history
	go func() {
		if err := c.chatRepo.SaveChatMessage(context.Background(), user.ID, "user", contextInfo); err != nil {
			slog.Error("Failed to save user message to chat history", "user_id", user.ID, "error", err)
		}
	}()

	// Agent loop: iterate until we get the final workout or hit max iterations
	for iteration := 0; iteration < maxIterations; iteration++ {
		slog.Info("Agent loop iteration", "user_id", user.ID, "iteration", iteration+1)

		// Inject current date/time into system prompt
		currentDate := c.now().Format("Monday, 02 January 2006")
		isoDate := c.now().Format("2006-01-02")
		enhancedSystemPrompt := fmt.Sprintf(`%s

CRITICAL TEMPORAL CONTEXT (TODAY):
Today is %s (ISO Format: %s). 

STRICT TIME CALCULATION RULE: 
The history data (JSON) ALWAYS comes in YYYY-MM-DD format. 
You MUST mathematically compare the history dates with today's date (%s). 
If the history returns the date %s, it means that workout was done TODAY, not yesterday or in the past. If the date matches today, acknowledge it correctly in your response.
If the date in the history matches TODAY's date (%s), you MUST refer to it as 'hoy' (today) or 'el entrenamiento que acabas de terminar' (the workout you just finished), respecting the LANGUAGE CONSISTENCY RULE (always in Spanish). It is STRICTLY FORBIDDEN to call it 'ayer' (yesterday) or treat it as a past day. NEVER assume the most recent history entry is from yesterday: always compute the difference in days against today's date.`, systemPrompt, currentDate, isoDate, isoDate, isoDate, isoDate)

		// Prepare streaming parameters
		params := anthropic.MessageNewParams{
			Model:       anthropic.Model(c.model),
			MaxTokens:   4096,
			Temperature: anthropic.Float(c.temperature),
			System: []anthropic.TextBlockParam{
				{
					Type: "text",
					Text: enhancedSystemPrompt,
				},
			},
			Messages: messages,
			Tools:    anthropicTools,
		}

		// Bound each Anthropic call so a stalled upstream cannot hang the request forever
		iterCtx, cancelIteration := context.WithTimeout(ctx, iterationTimeout)

		// Create streaming connection
		stream := c.client.Messages.NewStreaming(iterCtx, params)

		// Define state for handling multiple tools (parallel tool calling)
		type PendingTool struct {
			ID   string
			Name string
			JSON string
		}

		var fullMessage string
		var pendingTools []PendingTool
		var currentToolIndex = -1
		var stopReason string

		// Process streaming events
		for stream.Next() {
			event := stream.Current()

			switch event.Type {
			case "content_block_start":
				// Track when a new content block starts
				startEvent := event.AsContentBlockStart()
				if startEvent.ContentBlock.Type == "tool_use" {
					toolUseBlock := startEvent.ContentBlock.AsToolUse()
					pendingTools = append(pendingTools, PendingTool{
						ID:   toolUseBlock.ID,
						Name: toolUseBlock.Name,
						JSON: "",
					})
					currentToolIndex = len(pendingTools) - 1
					slog.Info("LLM tool called", "user_id", user.ID, "tool_name", toolUseBlock.Name, "tool_id", toolUseBlock.ID)
				}

			case "content_block_delta":
				deltaEvent := event.AsContentBlockDelta()
				if deltaEvent.Delta.Text != "" {
					// Stream text in realtime for the intro message
					fullMessage += deltaEvent.Delta.Text
					if onTextChunk != nil {
						onTextChunk(deltaEvent.Delta.Text)
					}
				} else if deltaEvent.Delta.PartialJSON != "" && currentToolIndex >= 0 {
					// Accumulate tool JSON silently for the current tool
					pendingTools[currentToolIndex].JSON += deltaEvent.Delta.PartialJSON
				}

			case "message_delta":
				// Capture stop reason when available
				deltaMsg := event.AsMessageDelta()
				if deltaMsg.Delta.StopReason != "" {
					stopReason = string(deltaMsg.Delta.StopReason)
				}

			case "message_stop":
				// Message completed and final message will be accumulated from events
			}
		}

		// Check for stream errors
		streamErr := stream.Err()
		stream.Close()
		cancelIteration()
		if err := streamErr; err != nil {
			slog.Error("Anthropic streaming error", "user_id", user.ID, "iteration", iteration+1, "error", err)
			return domain.Workout{}, fmt.Errorf("streaming error: %w", err)
		}

		slog.Info("LLM response completed", "user_id", user.ID, "stop_reason", stopReason)

		// Check for fast-exit markers in text responses
		if fullMessage == outOfScopeMarker {
			slog.Info("Out of scope query detected", "user_id", user.ID)
			return domain.Workout{
				ID:        fmt.Sprintf("workout_%d", time.Now().Unix()),
				UserID:    user.ID,
				Date:      c.now(),
				Message:   outOfScopeMessage,
				Exercises: []domain.Exercise{},
			}, nil
		}

		if fullMessage == unsupportedLanguageMarker {
			slog.Info("Unsupported language detected", "user_id", user.ID)
			return domain.Workout{
				ID:        fmt.Sprintf("workout_%d", time.Now().Unix()),
				UserID:    user.ID,
				Date:      c.now(),
				Message:   unsupportedLanguageMessage,
				Exercises: []domain.Exercise{},
			}, nil
		}

		// Reconstruct assistant message for conversation history
		var assistantBlocks []anthropic.ContentBlockParamUnion
		if fullMessage != "" {
			assistantBlocks = append(assistantBlocks, anthropic.NewTextBlock(fullMessage))
		}
		// Add all pending tools to the assistant message
		for _, pt := range pendingTools {
			var input map[string]interface{}
			if err := json.Unmarshal([]byte(pt.JSON), &input); err != nil {
				// If JSON is broken send an empty object to prevent crashing
				input = make(map[string]interface{})
			}
			assistantBlocks = append(assistantBlocks, anthropic.NewToolUseBlock(pt.ID, input, pt.Name))
		}
		messages = append(messages, anthropic.NewAssistantMessage(assistantBlocks...))

		// Check stop reason and process tools
		switch stopReason {
		case "tool_use":
			// Process all tool calls
			var finalWorkout *domain.Workout
			var userBlocks []anthropic.ContentBlockParamUnion

			for _, pt := range pendingTools {
				slog.Info("Processing tool execution", "user_id", user.ID, "tool_name", pt.Name)

				var toolResultContent string
				toolResultIsError := false

				switch pt.Name {
				case "update_user_status":
					slog.Info("LLM called update_user_status",
						"user_id", user.ID,
						"tool_arguments", pt.JSON)

					var statusInput struct {
						ReportedInjuries []string `json:"reported_injuries"`
						// TO DO: expand to set user preferences about workout durations, fatigue level or difficulty on workouts
					}

					// Parse Claude input
					if err := json.Unmarshal([]byte(pt.JSON), &statusInput); err == nil {
						// Update injuries in database
						errDB := c.userRepo.UpdateUserInjuries(ctx, user.ID, statusInput.ReportedInjuries)
						if errDB != nil {
							slog.Error("Failed to update injuries in database", "user_id", user.ID, "error", errDB)
						} else {
							slog.Info("Injuries updated successfully", "user_id", user.ID, "injuries", statusInput.ReportedInjuries)
						}
					}

					result := map[string]interface{}{
						"status":  "success",
						"message": "User status updated successfully",
					}
					resultJSON, _ := json.Marshal(result)
					toolResultContent = string(resultJSON)

				case "get_exercise_history":
					slog.Info("LLM called get_exercise_history",
						"user_id", user.ID,
						"tool_arguments", pt.JSON)

					// Fetch workout history from database
					workouts, err := c.workoutRepo.GetHistory(ctx, user.ID)
					if err != nil {
						slog.Error("Failed to retrieve exercise history", "user_id", user.ID, "error", err)
						// Return a sanitized error to Claude so raw database errors never reach the chat
						result := map[string]interface{}{
							"status":  "error",
							"message": toolInternalErrorMessage,
						}
						resultJSON, _ := json.Marshal(result)
						toolResultContent = string(resultJSON)
					} else {
						// Transform domain.Workout into a session-based structure so Claude
						// understands full workout context (fatigue, notes, and exercises together)
						history := []map[string]interface{}{}
						for _, workout := range workouts {
							exercises := []map[string]interface{}{}
							for _, exercise := range workout.Exercises {
								exercises = append(exercises, map[string]interface{}{
									"name":   exercise.DisplayName,
									"sets":   exercise.Sets,
									"reps":   exercise.Reps,
									"weight": exercise.Weight,
								})
							}

							history = append(history, map[string]interface{}{
								"date":          workout.Date.In(c.location).Format("2006-01-02"), // stored in UTC, shown in the users' timezone
								"fatigue_level": workout.FatigueLevel,
								"notes":         workout.Notes,
								"exercises":     exercises,
							})
						}

						result := map[string]interface{}{
							"status":  "success",
							"history": history,
						}
						resultJSON, _ := json.Marshal(result)
						toolResultContent = string(resultJSON)
						slog.Info("Exercise history retrieved", "user_id", user.ID, "workout_count", len(workouts))
					}

				case "get_allowed_exercises":
					slog.Info("LLM called get_allowed_exercises",
						"user_id", user.ID,
						"tool_arguments", pt.JSON)

					var catalogInput struct {
						MuscleGroup string `json:"muscle_group"`
					}

					if err := json.Unmarshal([]byte(pt.JSON), &catalogInput); err != nil {
						slog.Error("Failed to unmarshal get_allowed_exercises input", "user_id", user.ID, "error", err)
						result := map[string]interface{}{
							"status":  "error",
							"message": fmt.Sprintf("Failed to parse muscle group input: %v", err),
						}
						resultJSON, _ := json.Marshal(result)
						toolResultContent = string(resultJSON)
						break
					}

					catalogExercises, err := c.workoutRepo.GetAllowedExercises(ctx, catalogInput.MuscleGroup)
					if err != nil {
						slog.Error("Failed to retrieve allowed exercises", "user_id", user.ID, "muscle_group", catalogInput.MuscleGroup, "error", err)
						result := map[string]interface{}{
							"status":  "error",
							"message": toolInternalErrorMessage,
						}
						resultJSON, _ := json.Marshal(result)
						toolResultContent = string(resultJSON)
						break
					}

					allowedExercises := make([]map[string]interface{}, len(catalogExercises))
					for i, exercise := range catalogExercises {
						allowedExercises[i] = map[string]interface{}{
							"id":           exercise.ID,
							"name_es":      exercise.NameES,
							"muscle_group": exercise.MuscleGroup,
						}
					}

					result := map[string]interface{}{
						"status":            "success",
						"allowed_exercises": allowedExercises,
					}
					resultJSON, _ := json.Marshal(result)
					toolResultContent = string(resultJSON)
					slog.Info("Allowed exercises retrieved", "user_id", user.ID, "muscle_group", catalogInput.MuscleGroup, "exercise_count", len(catalogExercises))

				case "generate_workout_json":
					slog.Info("LLM executed workout json",
						"user_id", user.ID,
						"generated_payload", pt.JSON)

					// Parse the workout from tool arguments (using the accumulated pt.JSON)
					workout, err := c.parseWorkoutFromToolInput(json.RawMessage(pt.JSON), user.ID)
					if err != nil {
						var validationErr *workoutValidationError
						if errors.As(err, &validationErr) {
							// Business-rule violation: hand the problem back to Claude so it self-corrects
							// on the next iteration instead of failing the HTTP request
							slog.Warn("LLM workout failed validation, returning tool error to Claude", "user_id", user.ID, "error", validationErr)
							toolResultContent = validationErr.Error()
							toolResultIsError = true
							break
						}
						slog.Error("Failed to parse workout from LLM output", "user_id", user.ID, "error", err)
						return domain.Workout{}, fmt.Errorf("failed to parse workout: %w", err)
					}

					// Attach the streamed motivational message to the workout
					workout.Message = fullMessage
					finalWorkout = &workout

					// Send success confirmation back to Claude
					result := map[string]interface{}{
						"status":  "success",
						"message": "Workout generated successfully",
					}
					resultJSON, _ := json.Marshal(result)
					toolResultContent = string(resultJSON)

				case "log_workout_feedback":
					slog.Info("LLM called log_workout_feedback", "user_id", user.ID, "tool_arguments", pt.JSON)

					var feedbackInput struct {
						FatigueLevel int    `json:"fatigue_level"`
						Notes        string `json:"notes"`
					}

					if err := json.Unmarshal([]byte(pt.JSON), &feedbackInput); err != nil {
						slog.Error("Failed to unmarshal log_workout_feedback input", "user_id", user.ID, "error", err)
						result := map[string]interface{}{
							"status":  "error",
							"message": fmt.Sprintf("Failed to parse feedback input: %v", err),
						}
						resultJSON, _ := json.Marshal(result)
						toolResultContent = string(resultJSON)
						break
					}

					if err := c.workoutRepo.UpdateWorkoutFeedback(ctx, user.ID, feedbackInput.FatigueLevel, feedbackInput.Notes); err != nil {
						slog.Error("Failed to update workout feedback", "user_id", user.ID, "error", err)
						result := map[string]interface{}{
							"status":  "error",
							"message": toolInternalErrorMessage,
						}
						resultJSON, _ := json.Marshal(result)
						toolResultContent = string(resultJSON)
						break
					}

					slog.Info("Workout feedback logged successfully", "user_id", user.ID, "fatigue_level", feedbackInput.FatigueLevel)
					result := map[string]interface{}{
						"status":  "success",
						"message": "Workout feedback logged successfully",
					}
					resultJSON, _ := json.Marshal(result)
					toolResultContent = string(resultJSON)

				case "search_exercise_video":
					slog.Info("LLM called search_exercise_video", "user_id", user.ID, "tool_arguments", pt.JSON)
					var input struct {
						Query string `json:"query"`
					}
					var videoLink string
					if err := json.Unmarshal([]byte(pt.JSON), &input); err == nil {
						videoLink = youtube.SearchExerciseVideo(input.Query)
					}

					result := map[string]interface{}{
						"status":    "success",
						"video_url": videoLink,
					}
					resultJSON, _ := json.Marshal(result)
					toolResultContent = string(resultJSON)
				}

				// Add tool result block for this tool
				userBlocks = append(userBlocks, anthropic.NewToolResultBlock(pt.ID, toolResultContent, toolResultIsError))
			}

			// If we got the final workout, return it
			if finalWorkout != nil {
				slog.Info("Workout generated successfully by LLM", "user_id", user.ID, "workout_id", finalWorkout.ID, "exercise_count", len(finalWorkout.Exercises))

				// Save assistant message to chat history (Generator Mode)
				go func() {
					if err := c.chatRepo.SaveChatMessage(context.Background(), user.ID, "assistant", fullMessage); err != nil {
						slog.Error("Failed to save assistant message to chat history", "user_id", user.ID, "error", err)
					}
				}()

				return *finalWorkout, nil
			}

			// Add all tool results to conversation and continue loop
			if len(userBlocks) > 0 {
				messages = append(messages, anthropic.NewUserMessage(userBlocks...))
			}

		case "end_turn":
			// Claude finished without calling generate_workout_json
			// This could be either:
			// 1. A conversational response in Advisor Mode (valid)
			// 2. An actual out-of-scope query (invalid)

			if len(pendingTools) == 0 && fullMessage != "" {
				// Advisor Mode: Claude responded conversationally without generating a workout
				slog.Info("LLM streaming conversational response - Advisor Mode", "user_id", user.ID)

				// Save assistant message to chat history
				go func() {
					if err := c.chatRepo.SaveChatMessage(context.Background(), user.ID, "assistant", fullMessage); err != nil {
						slog.Error("Failed to save assistant message to chat history", "user_id", user.ID, "error", err)
					}
				}()

				return domain.Workout{
					ID:        fmt.Sprintf("workout_%d", time.Now().Unix()),
					UserID:    user.ID,
					Date:      c.now(),
					Message:   fullMessage,
					Exercises: []domain.Exercise{},
				}, nil
			}

			if len(pendingTools) == 0 && fullMessage == "" {
				// No tools called and no message it means out-of-scope
				slog.Info("Empty response from LLM - treating as out-of-scope", "user_id", user.ID)
				return domain.Workout{
					ID:        fmt.Sprintf("workout_%d", time.Now().Unix()),
					UserID:    user.ID,
					Date:      c.now(),
					Message:   outOfScopeMessage,
					Exercises: []domain.Exercise{},
				}, nil
			}

			// Tools were called but no workout was generated
			slog.Error("Agent finished without generating workout", "user_id", user.ID, "stop_reason", stopReason)
			return domain.Workout{}, fmt.Errorf("agent finished without generating workout")

		default:
			// Unexpected stop reason
			slog.Error("Unexpected stop reason from Anthropic", "user_id", user.ID, "stop_reason", stopReason)
			return domain.Workout{}, fmt.Errorf("unexpected stop reason: %s", stopReason)
		}
	}

	slog.Error("Max iterations reached without generating workout", "user_id", user.ID, "max_iterations", maxIterations)
	return domain.Workout{}, fmt.Errorf("max iterations reached without generating workout")
}

// workoutValidationError reports business-rule violations in the generate_workout_json arguments.
// Unlike a malformed payload, it is recoverable: the message is sent back to Claude as an error tool_result.
type workoutValidationError struct {
	Problems []string
}

func (e *workoutValidationError) Error() string {
	return "Error: invalid workout, fix the following and call generate_workout_json again: " + strings.Join(e.Problems, "; ")
}

// parseWorkoutFromToolInput converts the tool input JSON to a domain.Workout.
// It returns a *workoutValidationError when the arguments break business rules (e.g. negative sets, reps or weight).
func (c *AnthropicClient) parseWorkoutFromToolInput(input json.RawMessage, userID string) (domain.Workout, error) {
	var toolInput struct {
		UserID    string `json:"user_id"`
		Exercises []struct {
			ExerciseID  string  `json:"exercise_id"`
			DisplayName string  `json:"display_name"`
			Sets        int     `json:"sets"`
			Reps        int     `json:"reps"`
			Weight      float64 `json:"weight"`
		} `json:"exercises"`
	}

	if err := json.Unmarshal(input, &toolInput); err != nil {
		slog.Error("Failed to unmarshal workout tool input", "user_id", userID, "error", err)
		return domain.Workout{}, fmt.Errorf("failed to unmarshal tool input: %w", err)
	}

	var problems []string
	for i, ex := range toolInput.Exercises {
		label := fmt.Sprintf("exercise #%d (%s)", i+1, ex.ExerciseID)
		if ex.Sets < 0 {
			problems = append(problems, fmt.Sprintf("%s: sets cannot be negative (got %d)", label, ex.Sets))
		}
		if ex.Reps < 0 {
			problems = append(problems, fmt.Sprintf("%s: reps cannot be negative (got %d)", label, ex.Reps))
		}
		if ex.Weight < 0 {
			problems = append(problems, fmt.Sprintf("%s: weight cannot be negative (got %v); use 0 when there is no prior weight record", label, ex.Weight))
		}
	}
	if len(problems) > 0 {
		slog.Warn("Workout tool input failed validation", "user_id", userID, "problems", problems)
		return domain.Workout{}, &workoutValidationError{Problems: problems}
	}

	// Convert exercises
	exercises := make([]domain.Exercise, len(toolInput.Exercises))
	for i, ex := range toolInput.Exercises {
		exercises[i] = domain.Exercise{
			ExerciseID:  ex.ExerciseID,
			DisplayName: ex.DisplayName,
			Sets:        ex.Sets,
			Reps:        ex.Reps,
			Weight:      ex.Weight,
		}
	}

	workout := domain.Workout{
		ID:        fmt.Sprintf("workout_%d", time.Now().Unix()),
		UserID:    userID,
		Date:      c.now(), // server-side timestamp: LLM-generated dates are unreliable across timezones
		Message:   "",      // Message will come from Claude text response, not from tool
		Exercises: exercises,
	}

	return workout, nil
}
